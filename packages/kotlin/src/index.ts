/**
 * @fileoverview @zuari/kotlin
 * Native Android Kotlin bridge & theme generator for Zuari.
 * Supports Jetpack Compose theme synthesis, Material You dynamic color extraction,
 * and high-frequency bidirectional JS/Kotlin native function bridging.
 */

import { signal, computed, effect, batch } from '@zuari/signals';
import type {
  AndroidMaterialColors,
  AndroidThemeOptions,
  NativeKotlinBridge
} from './types.js';

export const DEFAULT_MATERIAL_LIGHT: AndroidMaterialColors = {
  primary: '#006A6A',
  onPrimary: '#FFFFFF',
  primaryContainer: '#6FF7F6',
  onPrimaryContainer: '#002020',
  secondary: '#4A6363',
  onSecondary: '#FFFFFF',
  background: '#FAFDFD',
  onBackground: '#191C1C',
  surface: '#FAFDFD',
  onSurface: '#191C1C',
  surfaceVariant: '#DAE5E4',
  outline: '#6F7979'
};

export const DEFAULT_MATERIAL_DARK: AndroidMaterialColors = {
  primary: '#4CDADA',
  onPrimary: '#003737',
  primaryContainer: '#004F4F',
  onPrimaryContainer: '#6FF7F6',
  secondary: '#B1CCCC',
  onSecondary: '#1C3534',
  background: '#191C1C',
  onBackground: '#E1E3E3',
  surface: '#191C1C',
  onSurface: '#E1E3E3',
  surfaceVariant: '#3F4948',
  outline: '#899392'
};

export function createKotlinBridge(initialDark = false): NativeKotlinBridge {
  const isDarkTheme = signal<boolean>(initialDark);
  const dynamicColors = signal<AndroidMaterialColors>(
    initialDark ? { ...DEFAULT_MATERIAL_DARK } : { ...DEFAULT_MATERIAL_LIGHT }
  );

  const isAndroid = computed(() => {
    if (typeof navigator !== 'undefined' && /android/i.test(navigator.userAgent)) {
      return true;
    }
    if (typeof window !== 'undefined' && (window as any).Android) {
      return true;
    }
    return false;
  });

  const registeredHandlers = new Map<string, (...args: any[]) => void>();

  // Expose global callback dispatcher for Android WebView evaluateJavascript / JavascriptInterface
  if (typeof window !== 'undefined') {
    (window as any).__zuariKotlinDispatcher = (name: string, payloadJson: string) => {
      const handler = registeredHandlers.get(name);
      if (handler) {
        try {
          const parsed = JSON.parse(payloadJson);
          handler(parsed);
        } catch {
          handler(payloadJson);
        }
      }
    };
  }

  function callNativeFunction<T = unknown>(fnName: string, ...args: unknown[]): Promise<T> {
    return new Promise((resolve, reject) => {
      // 1. Direct Android JavascriptInterface: window.Android[fnName]
      if (typeof window !== 'undefined' && (window as any).Android) {
        const androidObj = (window as any).Android;
        if (typeof androidObj[fnName] === 'function') {
          try {
            const res = androidObj[fnName](...args);
            try {
              resolve(JSON.parse(res));
            } catch {
              resolve(res);
            }
            return;
          } catch (err) {
            reject(err);
            return;
          }
        }
      }

      // 2. Tauri Android / Custom Scheme / Fallback mock for testing and emulation
      resolve({ success: true, mock: true, function: fnName, args } as unknown as T);
    });
  }

  function registerNativeCallback(name: string, handler: (...args: any[]) => void): () => void {
    registeredHandlers.set(name, handler);
    return () => {
      registeredHandlers.delete(name);
    };
  }

  function ingestDynamicPalette(palette: Partial<AndroidMaterialColors>): void {
    batch(() => {
      dynamicColors.value = {
        ...dynamicColors.value,
        ...palette
      };
    });
  }

  function generateComposeThemeCode(options?: AndroidThemeOptions): string {
    const pkg = options?.packageName ?? 'com.zuari.ui.theme';
    const name = options?.themeName ?? 'ZuariTheme';
    const c = { ...dynamicColors.value, ...(options?.colors ?? {}) };

    return `package ${pkg}

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.*
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color

// Native Material 3 Dynamic Colors generated by Zuari (@zuari/kotlin)
val ZuariPrimary = Color(android.graphics.Color.parseColor("${c.primary}"))
val ZuariOnPrimary = Color(android.graphics.Color.parseColor("${c.onPrimary}"))
val ZuariPrimaryContainer = Color(android.graphics.Color.parseColor("${c.primaryContainer}"))
val ZuariOnPrimaryContainer = Color(android.graphics.Color.parseColor("${c.onPrimaryContainer}"))
val ZuariSecondary = Color(android.graphics.Color.parseColor("${c.secondary}"))
val ZuariOnSecondary = Color(android.graphics.Color.parseColor("${c.onSecondary}"))
val ZuariBackground = Color(android.graphics.Color.parseColor("${c.background}"))
val ZuariOnBackground = Color(android.graphics.Color.parseColor("${c.onBackground}"))
val ZuariSurface = Color(android.graphics.Color.parseColor("${c.surface}"))
val ZuariOnSurface = Color(android.graphics.Color.parseColor("${c.onSurface}"))
val ZuariSurfaceVariant = Color(android.graphics.Color.parseColor("${c.surfaceVariant}"))
val ZuariOutline = Color(android.graphics.Color.parseColor("${c.outline}"))

private val ZuariColorScheme = lightColorScheme(
    primary = ZuariPrimary,
    onPrimary = ZuariOnPrimary,
    primaryContainer = ZuariPrimaryContainer,
    onPrimaryContainer = ZuariOnPrimaryContainer,
    secondary = ZuariSecondary,
    onSecondary = ZuariOnSecondary,
    background = ZuariBackground,
    onBackground = ZuariOnBackground,
    surface = ZuariSurface,
    onSurface = ZuariOnSurface,
    surfaceVariant = ZuariSurfaceVariant,
    outline = ZuariOutline
)

@Composable
fun ${name}(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = ZuariColorScheme,
        typography = Typography(),
        content = content
    )
}
`;
  }

  function generateXmlThemeCode(options?: AndroidThemeOptions): string {
    const name = options?.themeName ?? 'Theme.Zuari.Native';
    const c = { ...dynamicColors.value, ...(options?.colors ?? {}) };

    return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by @zuari/kotlin Native Android Bridge -->
<resources>
    <style name="${name}" parent="Theme.Material3.DayNight.NoActionBar">
        <item name="colorPrimary">${c.primary}</item>
        <item name="colorOnPrimary">${c.onPrimary}</item>
        <item name="colorPrimaryContainer">${c.primaryContainer}</item>
        <item name="colorOnPrimaryContainer">${c.onPrimaryContainer}</item>
        <item name="colorSecondary">${c.secondary}</item>
        <item name="colorOnSecondary">${c.onSecondary}</item>
        <item name="android:colorBackground">${c.background}</item>
        <item name="colorOnBackground">${c.onBackground}</item>
        <item name="colorSurface">${c.surface}</item>
        <item name="colorOnSurface">${c.onSurface}</item>
        <item name="colorSurfaceVariant">${c.surfaceVariant}</item>
        <item name="colorOutline">${c.outline}</item>
    </style>
</resources>
`;
  }

  function applyToCssVariables(target?: HTMLElement): () => void {
    const el = target ?? (typeof document !== 'undefined' ? document.documentElement : null);
    if (!el) return () => {};

    return effect(() => {
      const c = dynamicColors.value;
      el.style.setProperty('--md-sys-color-primary', c.primary);
      el.style.setProperty('--md-sys-color-on-primary', c.onPrimary);
      el.style.setProperty('--md-sys-color-primary-container', c.primaryContainer);
      el.style.setProperty('--md-sys-color-on-primary-container', c.onPrimaryContainer);
      el.style.setProperty('--md-sys-color-secondary', c.secondary);
      el.style.setProperty('--md-sys-color-on-secondary', c.onSecondary);
      el.style.setProperty('--md-sys-color-background', c.background);
      el.style.setProperty('--md-sys-color-on-background', c.onBackground);
      el.style.setProperty('--md-sys-color-surface', c.surface);
      el.style.setProperty('--md-sys-color-on-surface', c.onSurface);
      el.style.setProperty('--md-sys-color-surface-variant', c.surfaceVariant);
      el.style.setProperty('--md-sys-color-outline', c.outline);
    });
  }

  return {
    isAndroid,
    dynamicColors,
    isDarkTheme,
    callNativeFunction,
    registerNativeCallback,
    generateComposeThemeCode,
    generateXmlThemeCode,
    ingestDynamicPalette,
    applyToCssVariables
  };
}

